#!/usr/bin/env node
/* =========================================================================
   Refresh the casualty figures and dates baked into every page's <head>
   (title, meta description, Open Graph / Twitter cards, and the JSON-LD
   FAQPage / SpecialAnnouncement / WebPage blocks).

   Those numbers are what Google, Bing and social previews actually show, and
   they cannot be rendered client-side — so they have to be rewritten in the
   HTML whenever the situation figures move. The live page body updates itself
   from assets/live_data.json and the NDRRMA API; this script keeps the crawler-
   facing copy in step with the same baseline.

   Usage:  node tools/refresh_seo_figures.js
           node tools/refresh_seo_figures.js --dry     (report only, write nothing)

   How it works: FIGURES below lists the previous value → current value for each
   headline number, plus the date strings. Every replacement is an exact string
   swap, so nothing is guessed. After a real-world update, edit assets/
   live_data.json and this table together, then run the script.
   ========================================================================= */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DRY = process.argv.includes("--dry");

/* Previous value → current value. Order matters: longer/more specific strings
   must come before shorter ones that they contain. */
const FIGURES = [
  // --- dates -------------------------------------------------------------
  ["2026-08-30", "2026-08-31"],
  ["30 August 2026", "31 August 2026"],
  ["30 Aug 2026", "31 Aug 2026"],
  ["(NDRRMA, 30 Aug)", "(NDRRMA, 31 Aug)"],
  ["30 Aug)", "31 Aug)"],
  ["9 am on 30 August", "31 August"],

  // --- headline figures --------------------------------------------------
  ["8,186 rescued", "7,514 rescued"],
  ["2,498 missing", "4,247 missing"],
  ["734 confirmed dead", "903 confirmed dead"],
  ["734 dead", "903 dead"],
  ["734 deaths", "903 deaths"],
  ["2,498 people", "4,247 people"],
  ["19,895 security personnel", "18,708 security personnel"],
  ["19,895", "18,708"],
  ["8,186", "7,514"],
  ["2,498", "4,247"],
  ["2,189", "3,027"],
  ["2,034 Nepali", "2,801 Nepali"],
  ["155 foreign", "226 foreign"],
  ["242 injured", "1,473 injured"],
  ["668 foreign", "592 foreign"],
  ["734", "903"],
];

/* Longer prose swaps for the JSON-LD answer text and meta descriptions, applied
   before the numeric table so their wording stays coherent. */
const PROSE = [
  [
    "A glacial ice avalanche in Tibet near Gyirong, on the Nepal–China border, sent a catastrophic flash flood down the Bhote Koshi gorge into Rasuwa district on the morning of 26 August 2026.",
    "A glacier collapsed near Langtang Lirung inside Nepal, about 64 km north of Kathmandu, on the morning of 26 August 2026, sending a catastrophic flash flood down the Bhote Koshi gorge into Rasuwa district."
  ],
  [
    "The USGS attributed it to an ice avalanche or glacial process rather than an earthquake.",
    "Satellite imagery and USGS seismic analysis confirm a glacier collapse, not an earthquake: the Ms 5.2 signal recorded at 08:37 NPT was generated by the collapse itself."
  ],
  [
    "The missing include 933 people linked to hydropower projects and 589 foreign nationals.",
    "The missing include 934 people linked to hydropower projects, 592 foreign nationals and 85 security personnel."
  ],
  [
    "PM Disaster Relief Fund passes Rs 385.5 million",
    "PM Disaster Relief Fund passes Rs 5.44 billion"
  ],
  [
    "A glacial ice avalanche on the Nepal–China border sent a catastrophic flash flood down the Bhote Koshi and Trishuli rivers on 26 August 2026, killing hundreds across Rasuwa, Nuwakot, Dhading, Chitwan and Nawalparasi.",
    "A glacier collapse near Langtang Lirung inside Nepal sent a catastrophic flash flood down the Bhote Koshi and Trishuli rivers on 26 August 2026, killing hundreds across Rasuwa, Nuwakot, Dhading, Chitwan and Nawalparasi."
  ],
  [
    "2026 Nepal Floods (Bhotekoshi–Trishuli glacial flood)",
    "2026 Nepal Floods (Bhotekoshi–Trishuli glacier-collapse flood)"
  ],
  ["589 foreign nationals", "592 foreign nationals"],
  ["8,399 Nepali Army, 7,213 Nepal Police", "8,370 Nepali Army, 6,135 Nepal Police"],
  ["2,498 missing / out of contact", "4,247 missing / out of contact"],
  ["30 August after the Trishuli eroded its base", "30 August after the Trishuli eroded its base and remains cut"],
  ["30 Aug, Nepal side)", "31 Aug, Nepal side)"],
];

function run() {
  const files = fs.readdirSync(ROOT).filter(f => f.endsWith(".html"));
  let touched = 0, edits = 0;
  for (const f of files) {
    const p = path.join(ROOT, f);
    const before = fs.readFileSync(p, "utf8");
    let after = before;
    let n = 0;
    for (const [a, b] of PROSE.concat(FIGURES)) {
      if (a === b || !after.includes(a)) continue;
      n += after.split(a).length - 1;
      after = after.split(a).join(b);
    }
    if (after !== before) {
      touched++; edits += n;
      if (!DRY) fs.writeFileSync(p, after, "utf8");
      console.log(`${DRY ? "would update" : "updated"} ${f} (${n} replacements)`);
    }
  }
  console.log(`${DRY ? "dry run: " : ""}${touched} file(s), ${edits} replacement(s)`);
}

run();
